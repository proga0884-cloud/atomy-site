function renderCatalog(filter) {
  const grid = document.getElementById("catalogGrid");
  const items = PRODUCTS.filter(p => filter === "all" || p.category === filter);
  grid.innerHTML = items.map(p => `
    <article class="product reveal visible">
      <a class="product__img" href="https://www.atomy.ru/product/${p.code}" target="_blank" rel="noopener">
        <img src="${p.img}" alt="${p.name}" loading="lazy">
        <span class="product__badge">${p.badge}</span>
      </a>
      <div class="product__body">
        <span class="product__cat">${p.catLabel} · ${p.pv} PV</span>
        <h3 class="product__name">${p.name}</h3>
        <p class="product__desc">${p.desc}</p>
        <div class="product__bottom">
          <div>
            <span class="product__old">${p.oldPrice}</span>
            <span class="product__price">${p.price}</span>
          </div>
          <a href="#contact" class="btn btn--primary btn--sm">Заказать</a>
        </div>
      </div>
    </article>
  `).join("");
}

document.addEventListener("DOMContentLoaded", () => {
  renderCatalog("all");
  document.querySelectorAll(".filter").forEach(btn => {
    btn.addEventListener("click", () => {
      document.querySelectorAll(".filter").forEach(b => b.classList.remove("active"));
      btn.classList.add("active");
      renderCatalog(btn.dataset.filter);
    });
  });
});